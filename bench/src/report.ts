import type { WindowsResult } from './windows.js';
/** Renders the results as Markdown (pasted into ADR-001) next to the raw JSON. */

import { round } from './db.js';
import type { DdlResult, SafetyResult } from './ddl.js';
import type { BackupResult, CatalogResult, RlsSummary } from './ops.js';
import type { ReadResult } from './reads.js';
import type { LoadTimings, StorageSizes } from './schema.js';
import type { BulkResult, WriteResult } from './writes.js';

export interface Results {
  startedAt: string;
  durationSeconds: number;
  machine: Record<string, string | number>;
  postgres: { version: string; settings: Record<string, unknown>[] };
  config: Record<string, unknown>;
  load?: LoadTimings;
  storage?: StorageSizes;
  reads?: ReadResult[];
  links?: ReadResult[];
  rls?: RlsSummary;
  backup?: BackupResult[];
  writes?: { cells: WriteResult[]; bulk: BulkResult[] };
  ddl?: { ops: DdlResult[]; safety: SafetyResult };
  catalog?: CatalogResult;
  windows?: WindowsResult;
}

const mb = (bytes: number) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;
const ms = (value: number) => `${round(value)}`;
const ratio = (a: number, b: number) => (a > 0 ? `${(b / a).toFixed(1)}×` : 'n/a');

function table(header: string[], body: (string | number)[][]): string {
  const line = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...body.map(line)].join('\n');
}

function readTable(results: ReadResult[]): string {
  return table(
    ['Query', 'A median', 'A max', 'B median', 'B max', 'B / A', 'Same result'],
    results.map((r) => [
      r.name,
      ms(r.a.median),
      ms(r.a.max),
      ms(r.b.median),
      ms(r.b.max),
      ratio(r.a.median, r.b.median),
      r.match ? 'yes' : '**no**',
    ])
  );
}

export function renderMarkdown(r: Results): string {
  const out: string[] = [];
  out.push(`# Storage benchmark results (${r.startedAt.slice(0, 10)})`);
  out.push(
    '',
    `Generated by \`npm run bench\` in \`bench/\`; total run time ${Math.round(r.durationSeconds)} s. ` +
      'Times are milliseconds measured from the Node client (loopback TCP) unless stated otherwise. ' +
      '**A** = physical table per user table; **B** = shared JSONB records table.',
    '',
    '## Machine and configuration',
    '',
    table(
      ['Item', 'Value'],
      [
        ...Object.entries(r.machine).map(([k, v]) => [k, String(v)]),
        ['Postgres', r.postgres.version.split(' on ')[0] ?? r.postgres.version],
        ...r.postgres.settings.map((s) => [
          String(s['name']),
          `${String(s['setting'])}${s['unit'] ? ` (unit ${String(s['unit'])})` : ''}`,
        ]),
        ...Object.entries(r.config).map(([k, v]) => [`bench ${k}`, JSON.stringify(v)]),
      ]
    )
  );
  if (r.load && r.storage) {
    const l = r.load;
    const s = r.storage;
    out.push(
      '',
      '## Load and storage',
      '',
      table(
        ['Metric', 'A (physical)', 'B (JSONB)'],
        [
          [
            'Load data (s)',
            (l.aLoadMs / 1000).toFixed(1),
            `${(l.bLoadMs / 1000).toFixed(1)} (copied from A)`,
          ],
          ['Build indexes (s)', (l.aIndexMs / 1000).toFixed(1), (l.bIndexMs / 1000).toFixed(1)],
          ['Heap + TOAST', mb(s.aTableBytes), mb(s.bTableBytes)],
          ['Indexes', mb(s.aIndexBytes), mb(s.bIndexBytes)],
          ['Link junction table (incl. indexes)', mb(s.aJunctionBytes), 'inside the JSONB'],
          [
            'Total',
            mb(s.aTableBytes + s.aIndexBytes + s.aJunctionBytes),
            mb(s.bTableBytes + s.bIndexBytes),
          ],
          ['Average row size (bytes)', s.aAvgRowBytes, s.bAvgRowBytes],
          ['Link rows', l.junctionRows, l.junctionRows],
        ]
      )
    );
  }
  if (r.reads) out.push('', '## Reads (filter, sort, group, paging)', '', readTable(r.reads));
  if (r.links) out.push('', '## Links and rollups', '', readTable(r.links));
  if (r.writes) {
    out.push(
      '',
      '## Writes',
      '',
      table(
        [
          'Scenario',
          'Layout',
          'Writes/s',
          'p50',
          'p95',
          'p99',
          'max',
          'WAL bytes/write',
          'HOT %',
          'Lost updates',
        ],
        r.writes.cells.map((w) => [
          w.name,
          w.approach,
          w.perSecond,
          ms(w.latency.median),
          ms(w.latency.p95),
          ms(w.latency.p99),
          ms(w.latency.max),
          w.walBytesPerWrite,
          w.hotPercent ?? 'n/a',
          w.lostUpdates ?? 'n/a',
        ])
      ),
      '',
      'B-rmw is the legacy read-merge-write path (read the blob, change one key, write it back).',
      '',
      table(
        ['Bulk insert', 'Layout', 'Median', 'Max'],
        r.writes.bulk.map((b) => [
          `${b.rowsPerCall} rows, one statement`,
          b.approach,
          ms(b.latency.median),
          ms(b.latency.max),
        ])
      )
    );
  }
  if (r.ddl) {
    const s = r.ddl.safety;
    out.push(
      '',
      '## Schema changes under write load',
      '',
      'Four clients keep updating random rows of the same table while each operation runs. ' +
        '"Worst write" is the longest single update they saw, i.e. how long the table was effectively locked.',
      '',
      table(
        ['Operation', 'Layout', 'Duration', 'Worst write', 'Write p99', 'Writes during op', 'Note'],
        r.ddl.ops.map((d) => [
          d.name,
          d.approach,
          ms(d.opMs),
          ms(d.writerMaxMs),
          ms(d.writerP99Ms),
          d.writes,
          d.note ?? '',
        ])
      ),
      '',
      table(
        ['Safety check (A)', 'Result'],
        [
          [
            'ALTER TABLE + metadata INSERT rolled back together',
            s.transactionalRollback ? 'pass' : '**fail**',
          ],
          [
            `DDL queued behind an open reader, lock_timeout ${s.lockTimeoutSetting}`,
            `gave up after ${ms(s.ddlFailedAfterMs)} ms (${s.ddlErrorCode})`,
          ],
          ['A new reader queued behind that DDL waited', `${ms(s.readerWaitedMs)} ms`],
          ['Retry after the reader finished', `${ms(s.retryAfterReleaseMs)} ms`],
        ]
      )
    );
  }
  if (r.rls) {
    const i = r.rls.isolation;
    out.push(
      '',
      '## Row-level security',
      '',
      'A: policy compares `current_setting(app.workspace_id)` to a constant (no column). ' +
        'B: policy compares the `workspace_id` column. Queries run as a non-superuser role.',
      '',
      table(
        ['Query', 'A plain', 'A with RLS', 'B plain', 'B with RLS'],
        r.rls.cases.map((c) => [
          c.name,
          ms(c.aPlain.median),
          ms(c.aRls.median),
          ms(c.bPlain.median),
          ms(c.bRls.median),
        ])
      ),
      '',
      `Rows visible with another workspace set: A ${i.aOther}, B ${i.bOther}. With no workspace set: A ${i.aUnset}, B ${i.bUnset}.`
    );
  }
  if (r.backup) {
    out.push(
      '',
      '## Backup and restore (pg_dump -Fc, pg_restore -j 4)',
      '',
      table(
        ['Layout', 'Dump (s)', 'Dump size', 'Restore incl. indexes (s)', 'Rows restored'],
        r.backup.map((b) => [
          b.approach,
          b.dumpSeconds.toFixed(1),
          mb(b.dumpBytes),
          b.restoreSeconds.toFixed(1),
          b.restoredRows,
        ])
      )
    );
  }
  if (r.catalog) {
    const c = r.catalog;
    out.push(
      '',
      '## Many tables in one database (layout A, multi-tenant)',
      '',
      table(
        ['Metric', 'Value'],
        [
          [
            'User tables created (30 columns, pk, 1 index each)',
            `${c.tables} in ${c.schemas} schemas`,
          ],
          [
            'CREATE TABLE + index, median / p95 / max (ms)',
            `${ms(c.createMs.median)} / ${ms(c.createMs.p95)} / ${ms(c.createMs.max)}`,
          ],
          ['Total create time (s)', c.totalCreateSeconds.toFixed(1)],
          ['Relations added (pg_class rows)', c.relationsAdded],
          [
            'System catalog growth',
            `${mb(c.catalogBytesAdded)} (${(c.catalogBytesPerTable / 1024).toFixed(1)} kB per table)`,
          ],
          [
            'First query on a fresh connection, median / max (ms)',
            `${ms(c.coldFirstQueryMs.median)} / ${ms(c.coldFirstQueryMs.max)}`,
          ],
          [
            'pg_dump --schema-only of the whole DB (s)',
            c.schemaDumpSeconds === null ? 'skipped' : c.schemaDumpSeconds.toFixed(1),
          ],
          ['DROP SCHEMA … CASCADE for all (s)', c.dropSeconds.toFixed(1)],
        ]
      )
    );
  }
  if (r.windows) {
    const w = r.windows;
    out.push(
      '',
      '## Sorted and filtered windows with the field index job (layout A)',
      '',
      `100-row windows in the query compiler's shape, before and after the job's indexes (built with CREATE INDEX CONCURRENTLY: ${w.builds.map((b) => `${b.name} ${ms(b.ms)} ms`).join(', ')}). Targets are p95. **${w.pass ? 'All targets met.' : 'Some targets missed.'}**`,
      '',
      table(
        ['Window', 'Before p95', 'After median', 'After p95', 'Target p95', 'Met'],
        w.cases.map((c) => [
          c.name,
          ms(c.before.p95),
          ms(c.after.median),
          ms(c.after.p95),
          c.target,
          c.pass ? 'yes' : '**no**',
        ])
      )
    );
  }
  return `${out.join('\n')}\n`;
}
