import { z } from 'zod';
import { AI_MAX_TEXT, type AiOptions, aiOptionsSchema } from '../ai.js';
import { matchChoice } from '../choices.js';
import { NUMBER_OPERATORS } from '../number-like.js';
import type { FilterOperator } from '../types.js';
import {
  compareNullable,
  compareNumber,
  compareText,
  defineFieldType,
  first,
  formatNumber,
  MAX_NUMBER,
  parseNumberText,
  roundTo,
} from '../util.js';

/** An AI cell: a number (number output) or a text (text, summary, a choice's name). */
type AiCell = number | string;

function readNumberCell(v: unknown, o: AiOptions): number | null {
  const n = typeof v === 'number' ? v : typeof v === 'string' ? parseNumberText(v)?.value : null;
  if (typeof n !== 'number' || !Number.isFinite(n) || Math.abs(n) > MAX_NUMBER) return null;
  return o.precision === null ? n || 0 : roundTo(n, o.precision);
}

function readCell(input: unknown, o: AiOptions): AiCell | null {
  const v = first(input);
  if (o.output === 'number') return readNumberCell(v, o);
  const text =
    typeof v === 'string' ? v : typeof v === 'number' && Number.isFinite(v) ? String(v) : null;
  if (text === null) return null;
  if (o.output === 'singleSelect') {
    // Always one of the field's choices (by name, so formulas and filters read the name), or empty.
    const id = matchChoice(text, o.choices);
    return o.choices.find((c) => c.id === id)?.name ?? null;
  }
  const cut = text.slice(0, AI_MAX_TEXT);
  return cut.trim() === '' ? null : cut;
}

const compareCell = (a: AiCell, b: AiCell) => {
  if (typeof a === 'number' && typeof b === 'number') return compareNumber(a, b);
  if (typeof a === 'number') return -1;
  if (typeof b === 'number') return 1;
  return compareText(a, b);
};

const OPERATORS: readonly FilterOperator[] = [...NUMBER_OPERATORS, 'contains', 'doesNotContain'];

/**
 * An AI field: its value is generated by the workspace's AI provider from a prompt over the
 * record's other fields, in the worker (packages/server/src/ai/fields/), never typed in. Stored as
 * a `jsonb` number or text like a formula, so views sort and filter it; `generated` because its
 * values can't be computed again for free, so snapshots, restores and duplicates copy them.
 */
export const ai = defineFieldType({
  name: 'ai',
  label: 'AI',
  category: 'computed',
  optionsSchema: aiOptionsSchema,
  // The result's format, not the prompt or the fields it reads.
  publicOptions: (o) => ({ output: o.output, choices: o.choices, precision: o.precision }),
  storage: { kind: 'computed', sqlType: 'jsonb', generated: true },
  filterOperators: OPERATORS,
  sort: 'number',
  formulaType: 'any',
  editor: { kind: 'none', align: 'left', width: 220 },
  readOnly: true,
  computed: true,
  conversionInput: 'primitive',
  emptyValue: null,
  valueSchema: (o) =>
    o.output === 'number'
      ? z.number().refine((n) => Number.isFinite(n) && Math.abs(n) <= MAX_NUMBER)
      : o.output === 'singleSelect'
        ? z.string().refine((s) => o.choices.some((c) => c.name === s), 'Unknown choice')
        : z.string().min(1).max(AI_MAX_TEXT),
  coerce: readCell,
  toStorage: (value) => value,
  fromStorage: readCell,
  compare: (a, b) => compareNullable(a, b, compareCell),
  format: (value, o, ctx) => {
    if (value === null) return '';
    if (typeof value === 'string') return value;
    return formatNumber(value, ctx?.locale, {
      minimumFractionDigits: o.precision ?? 0,
      maximumFractionDigits: o.precision ?? 8,
    });
  },
  toPrimitive: (value) => value,
  apiType: () => 'aiText',
});
