/** Every contract, flat, with its `resource.name` key. */
export function allEndpoints(): { name: string; endpoint: EndpointDef }[] {
  return Object.entries(contracts).flatMap(([resource, group]) =>
    Object.entries(group).map(([name, endpoint]) => ({
      name: `${resource}.${name}`,
      endpoint: endpoint as EndpointDef,
    }))
  );
}
