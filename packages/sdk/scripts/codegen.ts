import { fileURLToPath } from 'node:url';
import {
  contracts,
  type EndpointDef,
  V1_BATCH_MAX,
  V1_PAGE_SIZE_MAX,
  V1ErrorSchema,
} from '@openrows/shared';
import { z } from 'zod';
import { biomeFormat } from './format.js';

/**
 * Generates `src/generated/v1.ts`, the SDK's types and endpoint table, from the REST API v1's
 * endpoint contracts in @openrows/shared: each contract's body and query (their input
 * shape) and response (their output shape) through Zod's JSON Schema, written as TypeScript. The
 * published SDK then needs neither Zod nor @openrows/shared. `npm run generate -w @openrows/sdk`
 * rewrites it; `codegen.test.ts` fails when it is out of date.
 */

type JsonSchema = {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  additionalProperties?: boolean | JsonSchema;
  items?: JsonSchema;
  prefixItems?: JsonSchema[];
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  allOf?: JsonSchema[];
  enum?: unknown[];
  const?: unknown;
  description?: string;
  $ref?: string;
};

/** The v1 resources, in the order the SDK's endpoint table lists them. */
export const V1_RESOURCES = [
  'v1Meta',
  'v1Records',
  'v1Comments',
  'v1Webhooks',
  'v1Automations',
] as const;

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const key = (name: string) => (IDENTIFIER.test(name) ? name : JSON.stringify(name));
const pascal = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function union(parts: string[]): string {
  const unique = [...new Set(parts)];
  return unique.length === 1 ? (unique[0] as string) : unique.join(' | ');
}

const wrap = (t: string) => (/[|&]/.test(t) ? `(${t})` : t);

function comment(description: string | undefined, indent: string): string {
  return description ? `${indent}/** ${description.replace(/\*\//g, '*\\/')} */\n` : '';
}

/** A JSON Schema (as Zod emits it) as a TypeScript type. */
export function toTs(s: JsonSchema, indent = ''): string {
  if (s.$ref) throw new Error(`codegen: unexpected $ref ${s.$ref}`);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return union(s.enum.map((v) => JSON.stringify(v)));
  if (s.anyOf || s.oneOf) return union((s.anyOf ?? s.oneOf ?? []).map((m) => toTs(m, indent)));
  if (s.allOf) return s.allOf.map((m) => wrap(toTs(m, indent))).join(' & ');
  if (Array.isArray(s.type)) return union(s.type.map((type) => toTs({ ...s, type }, indent)));
  switch (s.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      if (s.prefixItems) return `[${s.prefixItems.map((m) => toTs(m, indent)).join(', ')}]`;
      return `${wrap(s.items ? toTs(s.items, indent) : 'unknown')}[]`;
    case 'object':
      return objectTs(s, indent);
    case undefined:
      return 'unknown';
    default:
      throw new Error(`codegen: unexpected type ${s.type}`);
  }
}

function objectTs(s: JsonSchema, indent: string): string {
  const inner = `${indent}  `;
  const extra = s.additionalProperties;
  const rest =
    extra === undefined || extra === true ? 'unknown' : extra === false ? null : toTs(extra, inner);
  const props = Object.entries(s.properties ?? {});
  if (!props.length) return `Record<string, ${rest ?? 'never'}>`;
  const required = new Set(s.required ?? []);
  const lines = props.map(
    ([name, prop]) =>
      `${comment(prop.description, inner)}${inner}${key(name)}${required.has(name) ? '' : '?'}: ${toTs(prop, inner)};`
  );
  if (rest) lines.push(`${inner}[key: string]: ${rest};`);
  return `{\n${lines.join('\n')}\n${indent}}`;
}

function jsonSchema(schema: z.ZodType, io: 'input' | 'output'): JsonSchema {
  return z.toJSONSchema(schema, { io, unrepresentable: 'any' }) as JsonSchema;
}

function typeAlias(name: string, schema: z.ZodType, io: 'input' | 'output', doc: string): string {
  return `/** ${doc} */\nexport type ${name} = ${toTs(jsonSchema(schema, io))};\n`;
}

/** The generated module's source, formatted with the repository's Biome settings. */
export function generateV1Types(): string {
  const out: string[] = [
    '// Generated by `npm run generate -w @openrows/sdk` from the REST API v1 contracts in',
    '// @openrows/shared (packages/sdk/scripts/codegen.ts). Do not edit.',
    '',
    `/** Largest page of records or comments. */\nexport const V1_PAGE_SIZE_MAX = ${V1_PAGE_SIZE_MAX};`,
    `/** Most records one create, update, replace or delete request takes. */\nexport const V1_BATCH_MAX = ${V1_BATCH_MAX};`,
    '',
    typeAlias('V1ErrorBody', V1ErrorSchema, 'output', 'The body of every error answer.'),
  ];
  const table: string[] = [];
  for (const resource of V1_RESOURCES) {
    const endpoints = contracts[resource] as Record<string, EndpointDef>;
    const rows: string[] = [];
    for (const [name, e] of Object.entries(endpoints)) {
      const prefix = `${pascal(resource)}${pascal(name)}`;
      const doc = `${e.method} ${e.path}: ${e.summary}.`;
      if (e.body) out.push(typeAlias(`${prefix}Body`, e.body, 'input', `The body of ${doc}`));
      if (e.query && !e.queryArrays) {
        out.push(typeAlias(`${prefix}Query`, e.query, 'input', `The query of ${doc}`));
      }
      if (e.response) {
        out.push(typeAlias(`${prefix}Response`, e.response, 'output', `The answer of ${doc}`));
      }
      rows.push(
        `${name}: { method: ${JSON.stringify(e.method)}, path: ${JSON.stringify(e.path)}, status: ${e.status} },`
      );
    }
    table.push(`${resource}: {\n${rows.join('\n')}\n},`);
  }
  out.push(
    `/** Every v1 endpoint's method, path and success status. */\nexport const V1_ENDPOINTS = {\n${table.join('\n')}\n} as const;\n`
  );
  return format(out.join('\n'));
}

export const GENERATED_PATH = fileURLToPath(new URL('../src/generated/v1.ts', import.meta.url));

const format = (source: string) => biomeFormat(source, 'packages/sdk/src/generated/v1.ts');
