#!/usr/bin/env node
/**
 * Generates the brand's icons and social images from the traced rose mark,
 * docs/design/brand/logo-mark.svg (itself traced from docs/design/brand/logo.png). Run it after
 * changing the mark, then commit the results:
 *
 *   node scripts/brand-assets.mjs
 *
 * Writes into packages/client/public: favicon.svg, favicon.ico (16, 32, 48), apple-touch-icon.png
 * (180, on the light surface), icon-192.png, icon-512.png and icon-maskable-512.png (the web app
 * manifest's) and og-image.png / og-image-dark.png
 * (1200 x 630, rendered in Chromium with Inter); and the emails' mark,
 * packages/server/src/email/logo.ts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = (name) => resolve(root, 'packages/client/public', name);
const markSvg = readFileSync(resolve(root, 'docs/design/brand/logo-mark.svg'), 'utf8');
const path = /\sd="([^"]+)"/.exec(markSvg)?.[1];
if (!path) throw new Error('logo-mark.svg has no path');

const ROSE = '#E22651';
const PAPER = '#FAF7F5';
const CHARCOAL = '#17131A';

/** The mark on a square canvas: `inset` is the padding on each side, as a share of the side. */
function iconSvg({ inset = 0, background = null, radius = 0 }) {
  const size = 64 / (1 - 2 * inset);
  const offset = (size - 64) / 2;
  const bg = background
    ? `<rect width="${size}" height="${size}" rx="${radius * size}" fill="${background}"/>`
    : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}">${bg}<path transform="translate(${offset} ${offset})" fill="${ROSE}" d="${path}"/></svg>`;
}

async function png(svg, size) {
  return sharp(Buffer.from(svg), { density: 600 }).resize(size, size).png().toBuffer();
}

/** An ICO file of PNG-compressed images, which every current browser reads. */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4);
    header.writeUInt16LE(32, e + 6);
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((i) => i.data)]);
}

writeFileSync(
  out('favicon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><title>OpenRows</title><path fill="${ROSE}" d="${path}"/></svg>\n`
);
const tab = iconSvg({ inset: 0.02 });
writeFileSync(
  out('favicon.ico'),
  ico(await Promise.all([16, 32, 48].map(async (size) => ({ size, data: await png(tab, size) }))))
);
writeFileSync(
  out('apple-touch-icon.png'),
  await png(iconSvg({ inset: 0.16, background: PAPER }), 180)
);
const app = iconSvg({ inset: 0.14, background: PAPER, radius: 0.22 });
writeFileSync(out('icon-192.png'), await png(app, 192));
writeFileSync(out('icon-512.png'), await png(app, 512));
// Maskable icons keep the mark inside the middle 80% safe zone, on a full bleed.
writeFileSync(
  out('icon-maskable-512.png'),
  await png(iconSvg({ inset: 0.24, background: PAPER }), 512)
);
const emailLogo = await png(iconSvg({}), 96);
writeFileSync(
  resolve(root, 'packages/server/src/email/logo.ts'),
  `// Generated by scripts/brand-assets.mjs from docs/design/brand/logo-mark.svg: don't edit.

/** The rose mark for emails: a 96 px PNG shown at 24 px, attached inline by Content-ID. */
export const EMAIL_LOGO_PNG_BASE64 =
  '${emailLogo.toString('base64')}';
`
);

const inter = readFileSync(
  resolve(root, 'node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2')
).toString('base64');
function ogHtml({ bg, text, text2, tint }) {
  return `<!doctype html><html><head><style>
@font-face { font-family: Inter; src: url(data:font/woff2;base64,${inter}) format('woff2'); font-weight: 100 900; }
html, body { margin: 0; width: 1200px; height: 630px; }
body { background: ${bg}; font-family: Inter; color: ${text}; display: flex; flex-direction: column;
  justify-content: center; padding: 0 96px; box-sizing: border-box; position: relative; overflow: hidden; }
.glow { position: absolute; right: -180px; top: -160px; width: 720px; height: 720px; border-radius: 50%;
  background: radial-gradient(circle, ${tint} 0%, transparent 68%); }
.brand { display: flex; align-items: center; gap: 28px; position: relative; }
.brand svg { width: 132px; height: 132px; }
.word { font-size: 104px; font-weight: 700; letter-spacing: -0.02em; }
.line { margin-top: 44px; font-size: 40px; font-weight: 500; color: ${text2}; position: relative; letter-spacing: -0.01em; }
.top { position: absolute; left: 0; right: 0; top: 0; height: 10px; background: ${ROSE}; }
</style></head><body><div class="glow"></div><div class="top"></div>
<div class="brand"><svg viewBox="0 0 64 64"><path fill="${ROSE}" d="${path}"/></svg><span class="word">OpenRows</span></div>
<div class="line">The open-source Airtable alternative.<br>Self-host it or let us run it.</div>
</body></html>`;
}
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 630 } });
  for (const [name, colors] of [
    ['og-image.png', { bg: PAPER, text: '#1C1719', text2: '#6E6468', tint: '#FDECEF' }],
    [
      'og-image-dark.png',
      { bg: CHARCOAL, text: '#EEE8EA', text2: '#A89EA5', tint: 'rgba(226,38,81,0.18)' },
    ],
  ]) {
    await page.setContent(ogHtml(colors), { waitUntil: 'load' });
    await page.evaluate(() => document.fonts.ready);
    writeFileSync(out(name), await page.screenshot({ type: 'png' }));
  }
} finally {
  await browser.close();
}
console.log('brand assets written to packages/client/public');
